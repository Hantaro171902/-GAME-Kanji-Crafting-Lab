// Deterministic default so the first client render matches the SSR HTML.
// The stored language is applied after hydration in useLang's effect.
let current: Lang = "en";

function readStoredLang(): Lang {
  try {
    const v = localStorage.getItem(LANG_KEY);
    if (v === "ja" || v === "vi" || v === "en") return v;
  } catch {
    /* storage unavailable */
  }
  return "en";
}

const listeners = new Set<() => void>();

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  current = lang;
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    /* storage unavailable */
  }
  listeners.forEach((fn) => fn());
}

/** Subscribes the calling component to language changes. */
export function useLang(): Lang {
  const [lang, setLangState] = useState(current);
  useEffect(() => {
    // Apply the persisted language only after hydration so the first
    // client render matches the server-rendered HTML.
    const stored = readStoredLang();
    if (stored !== current) {
      current = stored;
      setLangState(stored);
    }
    const fn = () => setLangState(current);
    listeners.add(fn);
    return () => {
      listeners.delete(fn);
    };
  }, []);
  return lang;
}

/** Returns a translator bound to the current language. */
export function useT() {
  const lang = useLang();
  return useCallback(
    (key: string, params?: Record<string, string | number>) => {
      let s = UI[lang][key] ?? UI.en[key] ?? key;
      if (params) {
        for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
      }
      return s;
    },
    [lang],
  );
}

/** Picks the localized variant of a value. */
export function pick<T>(value: Localized<T>, lang: Lang): T {
  return value[lang] ?? value.en;
}